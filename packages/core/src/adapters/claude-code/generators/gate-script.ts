/**
 * The gate runtime written to .claude/hooks/context-canvas/gate.mjs. It reads
 * .context-canvas/lifecycle.json and is called by hooks in agent frontmatter
 * and by the /approve-gate-* skills. Plain Node (18+), no dependencies.
 *
 *   node gate.mjs stop <agent-slug>     Stop hook: run the CHECK gates of the stage this agent leads.
 *   node gate.mjs guard <agent-slug>    PreToolUse hook: block edits until earlier stages' gates pass.
 *   node gate.mjs approve <gate-slug>   Record a person's approval (from an /approve-gate-* skill).
 *   node gate.mjs status                Print every gate's state.
 *
 * Exit code 2 blocks: for Stop, Claude keeps working with stderr as feedback;
 * for PreToolUse, the tool call is refused and stderr explains why.
 *
 * Rubric gates with grader "jev" ask TypeSafe AI's Jev model one calibrated
 * yes/no question per criterion (POST {TYPESAFE_BASE_URL}/v1/systemone, key in
 * TYPESAFE_API_KEY). Without a key, or when the call fails, the gate falls back
 * to the self-assessed checklist and records why in its evidence file.
 */
export const GATE_SCRIPT = String.raw`#!/usr/bin/env node
// Generated by Context Canvas. Change the blueprint, not this file.
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Project layout: .claude/hooks/context-canvas/gate.mjs. Plugin layout: <plugin>/hooks/gate.mjs,
// with lifecycle.json at the plugin root. Gate state always lives in the project.
const scriptDir = dirname(fileURLToPath(import.meta.url));
const inProject = scriptDir.replace(/\\/g, "/").endsWith(".claude/hooks/context-canvas");
const root = process.env.CLAUDE_PROJECT_DIR || (inProject ? join(scriptDir, "..", "..", "..") : process.cwd());
const dir = join(root, ".context-canvas");
const lifecyclePath = [
  process.env.CLAUDE_PLUGIN_ROOT && join(process.env.CLAUDE_PLUGIN_ROOT, "lifecycle.json"),
  !inProject && join(scriptDir, "..", "lifecycle.json"),
  join(dir, "lifecycle.json"),
].find((path) => path && existsSync(path));
const lifecycle = JSON.parse(readFileSync(lifecyclePath || join(dir, "lifecycle.json"), "utf8"));
const stages = lifecycle.stages;
const artifactTitles = new Map((lifecycle.artifacts || []).map((artifact) => [artifact.slug, artifact.title]));
const JEV_URL = (process.env.TYPESAFE_BASE_URL || "https://api.typesafe.ai").replace(/\/+$/, "") + "/v1/systemone";

/** The agent a hook runs for: the argument, else agent_type from hook input (plugin agents are "plugin:name"). */
function agentOf(arg, input) {
  const raw = String(arg || input.agent_type || "");
  return raw.includes(":") ? raw.slice(raw.lastIndexOf(":") + 1) : raw;
}

function readJson(path, fallback) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return fallback;
  }
}

function writeJson(path, value) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(value, null, 2) + "\n");
}

function readStdin() {
  try {
    return JSON.parse(readFileSync(0, "utf8") || "{}");
  } catch {
    return {};
  }
}

const approvalPath = (gate) => join(dir, "approvals", gate.slug + ".json");
const assessmentPath = (gate) => join(dir, "evidence", gate.slug + ".md");
const evidencePath = (gate) => join(dir, "evidence", gate.slug + ".json");
const statePath = (stage) => join(dir, "state", stage.slug + ".json");

/** A blocking gate is satisfied by a recorded approval (people) or a passing run (checks). */
function gateSatisfied(gate) {
  if (!gate.blocking) return true;
  if (gate.type === "HUMAN_APPROVAL") return existsSync(approvalPath(gate));
  return readJson(evidencePath(gate), {}).passed === true;
}

/**
 * Rubric gates are self-assessed: the stage lead ticks each criterion it meets
 * in .context-canvas/evidence/<gate>.md ("- [x] <criterion>").
 */
function assessRubric(gate) {
  const path = assessmentPath(gate);
  const text = existsSync(path) ? readFileSync(path, "utf8").toLowerCase() : "";
  const lines = text.split("\n").map((line) => line.trim());
  const met = gate.criteria.filter((criterion) =>
    lines.some((line) => /^[-*] \[x\]/.test(line) && line.includes(criterion.toLowerCase()))
  ).length;
  const needed = Math.ceil((gate.passThreshold ?? 1) * gate.criteria.length);
  const passed = met >= needed;
  const checklist = gate.criteria.map((criterion) => "- [ ] " + criterion).join("\n");
  return {
    passed,
    met,
    message: "Gate \"" + gate.title + "\" needs a self-assessment: " + met + " of " + gate.criteria.length +
      " criteria are ticked, " + needed + " required. Check your output against each criterion and write .context-canvas/evidence/" +
      gate.slug + ".md with this checklist, ticking ([x]) only criteria you met and citing evidence:\n" + checklist,
  };
}

function readText(path, limit) {
  try {
    const text = readFileSync(path, "utf8");
    return text.length > limit ? text.slice(0, limit) + "\n[truncated]" : text;
  } catch {
    return null;
  }
}

/**
 * The stage's artifacts that are project files (titles such as "tasks.md"),
 * for the grader to read: what it produced first, then what it read, within
 * Jev's state budget.
 */
function stageFiles(stage) {
  const produced = {};
  const consumed = {};
  let budget = 48000;
  const collect = (slugs, into) => {
    for (const slug of slugs || []) {
      const title = artifactTitles.get(slug);
      if (!title || !/[./]/.test(title) || budget <= 0 || title in produced) continue;
      const text = readText(join(root, title), Math.min(budget, 16000));
      if (text === null) continue;
      into[title] = text;
      budget -= text.length;
    }
  };
  collect(stage.produces, produced);
  collect(stage.consumes, consumed);
  return { produced, consumed };
}

/**
 * Jev grading: one calibrated yes/no question per criterion, judged from the
 * stage's files and the lead's evidence. Returns { unavailable } when Jev
 * cannot be reached, so the caller falls back to the checklist.
 */
async function gradeWithJev(gate, stage) {
  const key = process.env.TYPESAFE_API_KEY;
  if (!key) return { unavailable: "TYPESAFE_API_KEY is not set" };
  const questions = {};
  gate.criteria.forEach((criterion, index) => {
    questions["criterion_" + index] = {
      type: "noul",
      instructions: "Judge the stage's produced files (use its input files as reference), not claims in the evidence that the work is done. Is this criterion met? " + criterion,
    };
  });
  const files = stageFiles(stage);
  const state = {
    stage: stage.title,
    gate: gate.title,
    producedFiles: files.produced,
    inputFiles: files.consumed,
    evidence: readText(assessmentPath(gate), 16000) || "(no evidence written)",
  };
  try {
    const response = await fetch(JEV_URL, {
      method: "POST",
      headers: { Authorization: "Bearer " + key, "Content-Type": "application/json" },
      body: JSON.stringify({ state, model: gate.model || "jev-latest", questions }),
      signal: AbortSignal.timeout(10000),
    });
    if (!response.ok) return { unavailable: "Jev returned HTTP " + response.status };
    const body = await response.json();
    const minProbability = gate.minProbability ?? 0.7;
    const results = gate.criteria.map((criterion, index) => {
      const answer = body.answers && body.answers["criterion_" + index];
      const probability = answer && typeof answer.noul === "number" ? answer.noul : null;
      return { criterion, probability, met: probability !== null && probability >= minProbability };
    });
    const met = results.filter((result) => result.met).length;
    const needed = Math.ceil((gate.passThreshold ?? 1) * gate.criteria.length);
    const unmet = results
      .filter((result) => !result.met)
      .map((result) => "- " + result.criterion + " (p=" + (result.probability === null ? "n/a" : result.probability.toFixed(2)) + ")");
    return {
      passed: met >= needed,
      met,
      grader: "jev",
      model: body.model || gate.model || "jev-latest",
      results,
      message: "Gate \"" + gate.title + "\": Jev judged " + met + " of " + gate.criteria.length + " criteria met (p >= " + minProbability +
        "), " + needed + " required. Not met yet:\n" + unmet.join("\n") + "\nImprove the output, note what changed in .context-canvas/evidence/" +
        gate.slug + ".md, and finish again.",
    };
  } catch (error) {
    return { unavailable: "Jev request failed: " + (error && error.message ? error.message : String(error)) };
  }
}

/** A rubric gate's result from its grader, falling back to the checklist when Jev is unavailable. */
async function gradeRubric(gate, stage) {
  if (gate.grader === "jev") {
    const graded = await gradeWithJev(gate, stage);
    if (!graded.unavailable) return graded;
    process.stderr.write("Gate \"" + gate.title + "\": " + graded.unavailable + "; using the self-assessed checklist instead.\n");
    return { ...assessRubric(gate), grader: "self", note: graded.unavailable };
  }
  return { ...assessRubric(gate), grader: "self" };
}

function block(message) {
  process.stderr.write(message + "\n");
  process.exit(2);
}

async function stop(arg) {
  const agentSlug = agentOf(arg, readStdin());
  if (!agentSlug) return;
  // The current stage is the first one this agent leads whose gates are not all satisfied.
  const stage = stages.find((candidate) => candidate.lead === agentSlug && !candidate.gates.every(gateSatisfied));
  if (!stage) return;
  const checks = stage.gates.filter((gate) => gate.type === "CHECK");
  const failures = [];
  for (const gate of stage.gates.filter((candidate) => candidate.type === "OUTCOME_RUBRIC")) {
    const result = await gradeRubric(gate, stage);
    writeJson(evidencePath(gate), {
      gate: gate.slug,
      passed: result.passed,
      met: result.met,
      total: gate.criteria.length,
      grader: result.grader,
      ...(result.model ? { model: result.model } : {}),
      ...(result.results ? { results: result.results } : {}),
      ...(result.note ? { note: result.note } : {}),
      at: new Date().toISOString(),
    });
    if (!result.passed && gate.blocking) failures.push(result.message);
  }
  for (const gate of checks) {
    const result = spawnSync(gate.command, { cwd: root, shell: true, encoding: "utf8", timeout: gate.timeoutSec * 1000 });
    const passed = result.status === 0;
    writeJson(evidencePath(gate), { gate: gate.slug, passed, command: gate.command, exitCode: result.status, at: new Date().toISOString() });
    if (!passed && gate.blocking) {
      const output = ((result.stdout || "") + (result.stderr || "")).trim().split("\n").slice(-30).join("\n");
      failures.push("Gate \"" + gate.title + "\" failed: " + gate.command + " exited " + result.status + (result.error ? " (" + result.error.message + ")" : "") + "\n" + output);
    }
  }
  const state = readJson(statePath(stage), { attempts: 0 });
  if (failures.length === 0) {
    writeJson(statePath(stage), { attempts: 0 });
    return;
  }
  const attempts = state.attempts + 1;
  const limit = stage.maxIterations || 3;
  // The attempt counter bounds the Stop-hook loop, whatever stop_hook_active says.
  if (attempts >= limit) {
    writeJson(statePath(stage), { attempts, escalated: true });
    process.stderr.write("Stage \"" + stage.title + "\" gates still fail after " + attempts + " attempts. Stopping so a person can decide.\n");
    return;
  }
  writeJson(statePath(stage), { attempts });
  block(failures.join("\n\n") + "\n\nFix the cause and finish again (attempt " + attempts + " of " + limit + ").");
}

function guard(arg) {
  const input = readStdin();
  const agentSlug = agentOf(arg, input);
  const target = String((input.tool_input && (input.tool_input.file_path || input.tool_input.notebook_path || input.tool_input.command)) || "");
  if (target.includes(".context-canvas/approvals")) {
    block("Approvals are recorded by people with the /approve-gate-* skills, not by agents.");
  }
  const assigned = stages.filter((stage) => stage.lead === agentSlug || stage.contributors.includes(agentSlug));
  if (assigned.length === 0) return;
  const earliest = Math.min(...assigned.map((stage) => stage.order));
  for (const stage of stages.filter((candidate) => candidate.order < earliest)) {
    for (const gate of stage.gates) {
      if (gateSatisfied(gate)) continue;
      const how = gate.type === "HUMAN_APPROVAL"
        ? "Ask a person to run /approve-gate-" + gate.slug + "."
        : gate.type === "CHECK"
          ? "Let the " + stage.title + " lead finish so its check runs."
          : "It needs its rubric evidence first.";
      block("Stage \"" + stage.title + "\" gate \"" + gate.title + "\" has not passed, so this stage cannot change files yet. " + how);
    }
  }
}

function approve(gateSlug, notes) {
  const stage = stages.find((candidate) => candidate.gates.some((gate) => gate.slug === gateSlug));
  const gate = stage && stage.gates.find((candidate) => candidate.slug === gateSlug);
  if (!gate) {
    console.log("No gate named " + gateSlug + " in this blueprint.");
    process.exit(1);
  }
  const git = (args) => spawnSync("git", args, { cwd: root, encoding: "utf8" }).stdout?.trim() || null;
  const approver = git(["config", "user.email"]) || process.env.USER || "unknown";
  writeJson(approvalPath(gate), {
    gate: gate.slug,
    stage: stage.slug,
    approvedBy: approver,
    approvedAt: new Date().toISOString(),
    commit: git(["rev-parse", "HEAD"]),
    notes: notes || "",
  });
  console.log("Recorded approval of \"" + gate.title + "\" (" + stage.title + ") by " + approver + ".");
}

function status() {
  for (const stage of stages) {
    for (const gate of stage.gates) {
      console.log(stage.order + ". " + stage.title + " / " + gate.title + ": " + (gateSatisfied(gate) ? "passed" : "pending") + (gate.blocking ? "" : " (advisory)"));
    }
  }
}

const [command, arg, ...rest] = process.argv.slice(2);
if (command === "stop") await stop(arg);
else if (command === "guard") guard(arg);
else if (command === "approve") approve(arg, rest.join(" "));
else if (command === "status") status();
else {
  console.error("usage: gate.mjs stop|guard <agent> | approve <gate> [notes] | status");
  process.exit(1);
}
`;
